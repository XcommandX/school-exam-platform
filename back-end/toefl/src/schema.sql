CREATE TABLE IF NOT EXISTS sessions(id TEXT PRIMARY KEY,expires INTEGER NOT NULL,user_id TEXT NOT NULL DEFAULT 'owner');
CREATE TABLE IF NOT EXISTS login_limits(id TEXT PRIMARY KEY,count INTEGER NOT NULL,reset INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS states(key TEXT PRIMARY KEY,value TEXT NOT NULL,revision INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS assessments(key TEXT PRIMARY KEY,value TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS recordings(key TEXT PRIMARY KEY,type TEXT NOT NULL,value BLOB NOT NULL);

CREATE TABLE IF NOT EXISTS users(id TEXT PRIMARY KEY,username TEXT NOT NULL UNIQUE COLLATE NOCASE,salt TEXT NOT NULL,password_hash TEXT NOT NULL,role TEXT NOT NULL DEFAULT 'user',created INTEGER NOT NULL);

CREATE TABLE IF NOT EXISTS account_activity(user_id TEXT PRIMARY KEY,value TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS invitations (
  id TEXT PRIMARY KEY,
  token_hash TEXT NOT NULL UNIQUE,
  created_by TEXT NOT NULL,
  created INTEGER NOT NULL,
  expires INTEGER NOT NULL,
  used_at INTEGER,
  used_by TEXT,
  revoked_at INTEGER
);
CREATE INDEX IF NOT EXISTS invitations_created ON invitations(created);
