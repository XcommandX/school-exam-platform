  const form = new FormData(); form.set('consent', 'true');
  await x.api.grade(form);
  assert.deepEqual(x.calls.map(call => call.url), ['/api/toefl/state', '/api/toefl/assess']);
  const failed = client(); await failed.c.initializeCloud(); failed.calls.length = 0;
  failed.c.fetch = async (url) => { failed.calls.push({ url }); return { ok: false, status: 503, json: async () => ({ error: 'unavailable' }) }; };
  failed.api.queue('four.history.v1', [{ id: 'attempt' }]);
  await assert.rejects(failed.api.grade(form), error => error.code === 'state_pending');
  assert(!failed.calls.some(call => call.url.endsWith('assess')));
  assert(bridge.indexOf('await initializeCloud()') < bridge.indexOf('await cloud.aiConfig()'));
