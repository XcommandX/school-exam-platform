  assert.match(panel, /界面演示（非真实 AI）/);
  assert.match(panel, /固定展示，不针对当前作答/);
  assert.doesNotMatch(panel, /DO NOT DISPLAY|5 \/ 5/);
  assert.equal(demo.c.validAssessment({ demo: true, score: 5 }), false);
  demo.h.ai = { [demo.r.key]: { q1: { demo: true, score: 5 } } };
  assert.equal(demo.c.window.FourLogic.recordProgress([demo.h]).get(demo.r.key).aiBest, null);
  vm.runInContext(fs.readFileSync(path.join(root, 'front-end/toefl/four-learning.js'), 'utf8'), demo.c);
