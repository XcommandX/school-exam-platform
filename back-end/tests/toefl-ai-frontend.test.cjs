const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const { webcrypto } = require('node:crypto');
const root = path.resolve(__dirname, '../..');
const source = fs.readFileSync(path.join(root, 'front-end/toefl/four-app.js'), 'utf8');
const logic = fs.readFileSync(path.join(root, 'front-end/toefl/four-logic.js'), 'utf8');
const clientSource = fs.readFileSync(path.join(root, 'front-end/toefl/clients/cloud-client.js'), 'utf8').replace('export async function', 'async function');
