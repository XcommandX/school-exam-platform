import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { mapQuestion, mapAttempt } from '../../src/integration/platform-adapter.mjs';

const bank = JSON.parse(await readFile(new URL('../../fixtures/anonymous-bank.json', import.meta.url), 'utf8'));
const questions = await Promise.all(bank.records.map(mapQuestion));
assert.equal(new Set(questions.map(q => q.questionId)).size, bank.records.length);
const original = bank.records[0];
assert.equal((await mapQuestion(Object.fromEntries(Object.entries(original).reverse()))).questionVersion, questions[0].questionVersion);
assert.notEqual((await mapQuestion({ ...original, title: 'Revised fixture' })).questionVersion, questions[0].questionVersion);
assert.deepEqual(questions[0].payload, original);
await assert.rejects(mapQuestion({ ...original, items: [original.items[0], original.items[0]] }), /Duplicate/);
const attempt = { id: 'fixture-attempt', queue: [questions[0].legacyKey], values: { q1: 'private fixture response' }, finished: 1792540800000, userId: 'untrusted-user' };
const context = { userId: 'verified-user', revision: 2 };
const mapped = await mapAttempt(attempt, context, questions);
assert.equal(mapped.userId, 'verified-user');
assert.equal(mapped.status, 'submitted');
assert.match(mapped.finishedAt, /Z$/);
assert.equal(mapped.scoreAuthority, 'client_reported');
assert.deepEqual(mapped.legacy, attempt);
assert.equal(mapped.idempotencyKey, (await mapAttempt(structuredClone(attempt), context, questions)).idempotencyKey);
assert.notEqual(mapped.idempotencyKey, (await mapAttempt(attempt, { ...context, revision: 3 }, questions)).idempotencyKey);
assert.notEqual(mapped.idempotencyKey, (await mapAttempt(attempt, { ...context, userId: 'another-user' }, questions)).idempotencyKey);
await assert.rejects(mapAttempt(attempt, {}, questions), /identifier/);
await assert.rejects(mapAttempt({ ...attempt, queue: ['missing'] }, context, questions), /Unresolved/);
await assert.rejects(mapAttempt({ ...attempt, finished: 'invalid' }, context, questions), /timestamp/);
const pending = await mapAttempt({ id: 'draft', queue: attempt.queue }, context, questions);
assert.equal(pending.status, 'in_progress');
assert.equal(pending.startedAt, null);
assert.equal(pending.finishedAt, null);
console.log('PASS: namespaced IDs, content versions, preserved legacy data, UTC timestamps and account/revision-scoped retry keys.');
